"""FoundationPose meshes for the LEGO bricks: textured OBJs from the SAME geometry the sim builds (pnp_core/brick.py).

    python3 /repo/tools/make_brick_meshes.py        -> models/foundationpose/meshes/<lego_*>/{mesh.obj, mesh.mtl, texture.png}

The YCB objects' meshes are exported from their USD assets (sim/export_mesh.py); a brick is procedural in the sim
(box + studs, sim/scene.py add_brick), so its mesh is generated from the same numbers instead. Frame = the brick
prim's frame (TF `target` in the sim): origin at the bounding-box center incl. studs, z up. Color: the object's
`color` (linear, what the sim material takes) converted to sRGB, the way it shows up in a camera image. For real
bricks with a different shade, change `color` in config/objects.yaml (or the texture) and regenerate.
config/foundationpose.yaml `meshes:` lists them (docs/learning/10_6d_pose.md, 17_so101.md).
"""

import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, "/repo")
from pnp_core.brick import brick_mesh, linear_to_srgb  # noqa: E402
from pnp_core.catalog import load_yaml, repo_root  # noqa: E402


def write_obj(out: Path, name: str, V: np.ndarray, F: np.ndarray, rgb) -> None:
    out.mkdir(parents=True, exist_ok=True)
    tex = np.tile(np.round(np.asarray(rgb) * 255).astype(np.uint8), (8, 8, 1))     # one solid color
    Image.fromarray(tex).save(out / "texture.png")
    (out / "mesh.mtl").write_text("newmtl material0\nKa 1 1 1\nKd 1 1 1\nKs 0 0 0\nmap_Kd texture.png\n")
    with open(out / "mesh.obj", "w") as f:
        f.write(f"# {name}: generated by tools/make_brick_meshes.py (pnp_core/brick.py; frame = the sim's brick prim)\n")
        f.write("mtllib mesh.mtl\nusemtl material0\n")
        f.writelines(f"v {x:.6f} {y:.6f} {z:.6f}\n" for x, y, z in V)
        f.writelines("vt 0.5 0.5\n" for _ in V)                 # every vertex samples the solid texture
        f.writelines(f"f {a + 1}/{a + 1} {b + 1}/{b + 1} {c + 1}/{c + 1}\n" for a, b, c in F)


def main():
    objects = load_yaml("config/objects.yaml")
    root = repo_root() / "models/foundationpose/meshes"
    for name, cfg in objects.items():
        if "brick" not in cfg:
            continue
        V, F = brick_mesh(cfg)
        rgb = linear_to_srgb(cfg.get("color", [0.8, 0.1, 0.1]))
        write_obj(root / name, name, V, F, rgb)
        ext = V.max(0) - V.min(0)
        print(f"{name}: {len(V)} vertices, {len(F)} triangles, extent {np.round(ext * 1000, 1).tolist()} mm "
              f"(dims_m {[round(d * 1000, 1) for d in cfg['dims_m']]}), color sRGB {np.round(rgb, 2).tolist()}")


if __name__ == "__main__":
    main()
